"""Alembic round trip on a dedicated `_mig` database (AC4), so `downgrade base` never touches
the tables the other integration tests use."""

from collections.abc import Iterator

import pytest
from alembic import command
from alembic.util.exc import AutogenerateDiffsDetected
from sqlalchemy import create_engine, inspect, text
from sqlalchemy.engine import make_url

from tests.conftest import TEST_DATABASE_URL, alembic_config, drop_database, ensure_database


@pytest.fixture
def migration_db_url() -> Iterator[str]:
    url = make_url(TEST_DATABASE_URL)
    mig_url = url.set(database=f"{url.database}_mig").render_as_string(hide_password=False)
    drop_database(mig_url)
    ensure_database(mig_url)
    yield mig_url
    drop_database(mig_url)


def _table_names(url: str) -> set[str]:
    engine = create_engine(url)
    try:
        return set(inspect(engine).get_table_names())
    finally:
        engine.dispose()


def test_ac4_migration_roundtrip(migration_db_url: str) -> None:
    cfg = alembic_config(migration_db_url)

    command.upgrade(cfg, "head")
    assert "areas" in _table_names(migration_db_url)

    command.downgrade(cfg, "base")
    assert "areas" not in _table_names(migration_db_url)

    command.upgrade(cfg, "head")
    assert "areas" in _table_names(migration_db_url)


# What the postgis/postgis image installs into its default database: topology and the tiger
# geocoder, whose tables become visible through the database-level `search_path`.
_POSTGIS_IMAGE_SETUP = (
    "CREATE EXTENSION IF NOT EXISTS postgis",
    "CREATE EXTENSION IF NOT EXISTS postgis_topology",
    "CREATE EXTENSION IF NOT EXISTS fuzzystrmatch",
    "CREATE EXTENSION IF NOT EXISTS postgis_tiger_geocoder",
)


def test_ac4_autogenerate_sees_no_diff_with_postgis_extensions(migration_db_url: str) -> None:
    engine = create_engine(migration_db_url, isolation_level="AUTOCOMMIT")
    try:
        with engine.connect() as conn:
            for statement in _POSTGIS_IMAGE_SETUP:
                conn.execute(text(statement))
            name = make_url(migration_db_url).database
            conn.execute(
                text(f'ALTER DATABASE "{name}" SET search_path = "$user", public, topology, tiger')
            )
            assert (
                conn.execute(
                    text("SELECT count(*) FROM pg_tables WHERE schemaname IN ('tiger', 'topology')")
                ).scalar_one()
                > 0
            )
    finally:
        engine.dispose()
    cfg = alembic_config(migration_db_url)
    command.upgrade(cfg, "head")

    try:
        command.check(cfg)
    except AutogenerateDiffsDetected as exc:  # pragma: no cover - the failure message is the point
        pytest.fail(f"autogenerate would emit operations against a migrated DB: {exc}")


def test_ac4_migration_creates_gist_index_on_geom(migration_db_url: str) -> None:
    command.upgrade(alembic_config(migration_db_url), "head")

    engine = create_engine(migration_db_url)
    try:
        with engine.connect() as conn:
            method = conn.execute(
                text(
                    "SELECT am.amname FROM pg_class i"
                    " JOIN pg_am am ON am.oid = i.relam"
                    " JOIN pg_index x ON x.indexrelid = i.oid"
                    " WHERE i.relname = 'ix_areas_geom' AND x.indrelid = 'areas'::regclass"
                )
            ).scalar_one_or_none()
    finally:
        engine.dispose()

    assert method == "gist"


def test_ac13_users_sessions_roundtrip(migration_db_url: str) -> None:
    cfg = alembic_config(migration_db_url)

    command.upgrade(cfg, "head")
    command.downgrade(cfg, "base")
    assert not {"users", "sessions"} & _table_names(migration_db_url)
    command.upgrade(cfg, "head")

    assert {"users", "sessions"} <= _table_names(migration_db_url)
    engine = create_engine(migration_db_url)
    try:
        with engine.connect() as conn:
            constraints = set(
                conn.execute(
                    text(
                        "SELECT conname FROM pg_constraint"
                        " WHERE conrelid = 'users'::regclass AND contype = 'c'"
                    )
                ).scalars()
            )
            indexes = set(
                conn.execute(
                    text("SELECT indexname FROM pg_indexes WHERE tablename = 'sessions'")
                ).scalars()
            )
            on_delete = conn.execute(
                text(
                    "SELECT confdeltype FROM pg_constraint"
                    " WHERE conrelid = 'sessions'::regclass AND contype = 'f'"
                )
            ).scalar_one()
    finally:
        engine.dispose()

    assert {
        "ck_users_display_name_length",
        "ck_users_role",
        "ck_users_account_type",
    } <= constraints
    assert "ix_sessions_user_id" in indexes
    assert on_delete == "c"  # ON DELETE CASCADE


