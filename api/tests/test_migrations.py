    # Spec 0015a: `safe_room` true becomes `shelter = 'mamad'`; false and NULL become NULL ("no
    # ממ״ד" says nothing about a ממ״ק or a מקלט); the column goes. Downgrade: `safe_room` is true
    # for a `mamad` row and NULL for every other (a lost `false` is not recovered).
    cfg = alembic_config(migration_db_url)
    command.upgrade(cfg, "0022")
    engine = create_engine(migration_db_url)
    try:
        ids = _listing_shelter_world(engine)

        command.upgrade(cfg, "0023")
        with engine.begin() as conn:
            assert "safe_room" not in _columns(conn, "listings")
            shelters = dict(conn.execute(text("SELECT id, shelter FROM listings")).tuples().all())
            assert shelters == {ids["yes"]: "mamad", ids["no"]: None, ids["unsaid"]: None}
            # Another shelter type never turns into a ממ״ד on the way down.
            conn.execute(
                text("UPDATE listings SET shelter = 'mamak' WHERE id = :id"), {"id": ids["no"]}
            )

        command.downgrade(cfg, "0022")
        with engine.connect() as conn:
            columns = _columns(conn, "listings")
            assert "shelter" not in columns
            assert columns["safe_room"] is True
            safe_rooms = dict(
                conn.execute(text("SELECT id, safe_room FROM listings")).tuples().all()
            )
            assert safe_rooms == {ids["yes"]: True, ids["no"]: None, ids["unsaid"]: None}
    finally:
        engine.dispose()
