_LOCATION_COLUMNS = {"location", "geocode_status", "geocode_attempts"}


def _listing_columns(conn: Any) -> set[str]:
    return set(
        conn.execute(
            text(
                "SELECT column_name FROM information_schema.columns"
                " WHERE table_schema = 'public' AND table_name = 'listings'"
            )
        ).scalars()
    )


def _location_index_method(conn: Any) -> str | None:
    method: str | None = conn.execute(
        text(
            "SELECT am.amname FROM pg_class i"
            " JOIN pg_am am ON am.oid = i.relam"
            " JOIN pg_index x ON x.indexrelid = i.oid"
            " WHERE i.relname = 'ix_listings_location' AND x.indrelid = 'listings'::regclass"
        )
    ).scalar_one_or_none()
    return method


def test_ac1_listing_location_migration_roundtrip(migration_db_url: str) -> None:
    cfg = alembic_config(migration_db_url)
    command.upgrade(cfg, "0003")
    engine = create_engine(migration_db_url)
    try:
        with engine.begin() as conn:
            area_id = conn.execute(
                text(
                    "INSERT INTO areas (slug, name_he, geom)"
                    " VALUES ('gush-dan', 'gd', ST_GeomFromText(:wkt, 4326)) RETURNING id"
                ),
                {"wkt": GUSH_DAN_WKT},
            ).scalar_one()
            owner_id = conn.execute(
                text(
                    "INSERT INTO users (email, display_name, role)"
                    " VALUES ('owner@example.com', 'owner', 'owner') RETURNING id"
                )
            ).scalar_one()
            listing_id = conn.execute(
                text(
                    "INSERT INTO listings (owner_id, area_id, listing_type, city, street, rooms,"
                    " floor, size_sqm, price_ils, available_from, elevator, furnished,"
                    " pets_allowed, expires_at)"
                    " VALUES (:owner, :area, 'apartment', 'city', 'street', 3, 1, 80, 6000,"
                    " current_date, false, 'none', false, now() + interval '90 days')"
                    " RETURNING id"
                ),
                {"owner": owner_id, "area": area_id},
            ).scalar_one()

        command.upgrade(cfg, "0004")
        with engine.connect() as conn:
            row = conn.execute(
                text(
                    "SELECT geocode_status, geocode_attempts, location IS NULL"
                    " FROM listings WHERE id = :id"
                ),
                {"id": listing_id},
            ).one()
            assert tuple(row) == ("pending", 0, True)
            assert _location_index_method(conn) == "gist"
            # On the planar cast the map box compares (services/search.py); autogenerate does not
            # compare index expressions, so this pins the model's and the migration's.
            assert (
                conn.execute(
                    text("SELECT indexdef FROM pg_indexes WHERE indexname = 'ix_listings_location'")
                )
                .scalar_one()
                .endswith("USING gist (((location)::geometry))")
            )
        (model_index,) = (
            i for i in Base.metadata.tables["listings"].indexes if i.name == "ix_listings_location"
        )
        assert [str(e) for e in model_index.expressions] == ["(location::geometry)"]
        for assignment, constraint in (
            ("geocode_status = 'ok'", "ck_listings_location_status"),
            ("geocode_attempts = 6", "ck_listings_geocode_attempts"),
        ):
            with pytest.raises(IntegrityError, match=constraint), engine.begin() as conn:
                conn.execute(
                    text(f"UPDATE listings SET {assignment} WHERE id = :id"), {"id": listing_id}
                )

        command.downgrade(cfg, "0003")
        with engine.connect() as conn:
            assert not _LOCATION_COLUMNS & _listing_columns(conn)
            assert _location_index_method(conn) is None
            assert (
                conn.execute(
                    text("SELECT count(*) FROM listings WHERE id = :id"), {"id": listing_id}
                ).scalar_one()
                == 1
            )

        command.upgrade(cfg, "head")
        with engine.connect() as conn:
            assert _listing_columns(conn) >= _LOCATION_COLUMNS
    finally:
        engine.dispose()


